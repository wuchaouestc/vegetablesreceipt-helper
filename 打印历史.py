# -*- coding: utf-8 -*-
"""打印历史 —— **本次开机以来**打过的每一张标签（内存里的账）。

为什么要有它
------------
用户要的是「补打」：标签纸脱落沾到别处、贴坏了撕不下来、或者干脆损坏，
都要能只重打那一张，而不是把整批再来一遍。整批重打 = 浪费纸 + 分不清哪张是
新的哪张是重复的。

为什么只在内存、断电就没
------------------------
一天约 21 张，一批 3~4 张。会要补打的，几乎都是「刚打完就发现坏了」——
所以本次开机足够。跨天/跨重启要查的是「打过什么、几点」，那件事由
`打单记录.py` 写进 txt 文件，两者是分工，不是重复：
    · 打印历史（本模块）：用来**重打**，内存，关机即清
    · 打单记录（打单记录.py）：用来**查账**，落盘，按天按客户分文件

上限 400 行：一天约 21 张（七家 × 名牌 + 单据），够两周不重启的量。
超了就丢最旧的 —— 内存里的东西不能无限长。
"""

from __future__ import annotations

from datetime import datetime

上限 = 400
_条 = []          # 新的在前
_下个号 = 1


def 清空():
    """把历史清空（测试用；生产上只有重启才会是空的）。"""
    global _条, _下个号
    _条 = []
    _下个号 = 1


def 加(客户, 类型, 品类, 编码, 斤数, 单位, 备注, 图, 结果, 时间):
    """记一张。返回记下来的那条（带上 id）。"""
    global _下个号, _条
    条 = {
        'id': _下个号,
        '客户': 客户, '类型': 类型, '品类': 品类, '编码': 编码,
        '斤数': 斤数, '单位': 单位, '备注': 备注, '图': 图, '结果': 结果,
        '时间': 时间,
    }
    _下个号 += 1
    _条.insert(0, 条)
    if len(_条) > 上限:
        _条 = _条[:上限]
    return 条


def 列表(客户=None):
    """**新的在前**（界面要最新一条在最上面）。可按客户过滤。"""
    if 客户 is None:
        return list(_条)
    return [t for t in _条 if t.get('客户') == 客户]


def 取(编号):
    for t in _条:
        if t.get('id') == 编号:
            return t
    return None


def 条数(客户=None):
    return len(列表(客户))


def 转记录(条目):
    """把一条历史转成 `_print_task` 认得的记录（只带 5 个业务字段 + 客户）。

    ⚠️ 客户必须跟着**这一条自己**走：在南波旺状态下去补打一张中惠的标签，
       记录要落进中惠的文件、名牌也不能打错人。
    """
    return {
        'category': 条目.get('品类', ''),
        'code': 条目.get('编码', ''),
        'weight': 条目.get('斤数', ''),
        'unit': 条目.get('单位', ''),
        'remark': 条目.get('备注', ''),
        'customer': 条目.get('客户', ''),
        'type': 条目.get('类型', '单据'),
    }
