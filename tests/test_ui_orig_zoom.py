"""原图缩放补丁的纯逻辑测试：缩放围绕鼠标位置、拖动偏移计算。

界面绘制依赖 Tk 和真实图片，这里只测「缩放/偏移」的数学模型是否正确——
这是缩放拖动最容易出错的地方（缩放了图片会跳、拖了会漂）。
"""
import math
import unittest

_最小缩放 = 0.2
_最大缩放 = 8.0
_缩放步进 = 1.1


def 围绕鼠标缩放(旧缩放, 旧偏移, 鼠标x, 鼠标y, 方向):
    """与补丁里 _原图滚轮 同一套公式。方向：+1 放大，-1 缩小。"""
    if 方向 > 0:
        新缩放 = min(_最大缩放, 旧缩放 * _缩放步进)
    else:
        新缩放 = max(_最小缩放, 旧缩放 / _缩放步进)
    比例 = 新缩放 / 旧缩放
    新偏移x = 鼠标x - (鼠标x - 旧偏移[0]) * 比例
    新偏移y = 鼠标y - (鼠标y - 旧偏移[1]) * 比例
    return 新缩放, (新偏移x, 新偏移y)


def 拖动偏移(起点偏移, 起点鼠标, 当前鼠标):
    return (起点偏移[0] + (当前鼠标[0] - 起点鼠标[0]),
            起点偏移[1] + (当前鼠标[1] - 起点鼠标[1]))


class 缩放模型测试(unittest.TestCase):
    def test_滚轮向上放大(self):
        缩放, _ = 围绕鼠标缩放(1.0, (0, 0), 100, 100, +1)
        self.assertAlmostEqual(缩放, 1.1)

    def test_滚轮向下缩小(self):
        缩放, _ = 围绕鼠标缩放(1.0, (0, 0), 100, 100, -1)
        self.assertAlmostEqual(缩放, 1.0 / 1.1)

    def test_放大到上限不再增长(self):
        缩放, _ = 围绕鼠标缩放(_最大缩放, (0, 0), 0, 0, +1)
        self.assertEqual(缩放, _最大缩放)

    def test_缩小到下限不再减小(self):
        缩放, _ = 围绕鼠标缩放(_最小缩放, (0, 0), 0, 0, -1)
        self.assertEqual(缩放, _最小缩放)

    def test_中心缩放时图片中心不动(self):
        """鼠标正好在图片中心（偏移 0 处），缩放后偏移仍为 0。"""
        _, 偏移 = 围绕鼠标缩放(1.0, (0, 0), 0, 0, +1)
        self.assertAlmostEqual(偏移[0], 0.0)
        self.assertAlmostEqual(偏移[1], 0.0)

    def test_围绕非中心点缩放保持锚点不动(self):
        """鼠标在画布 (100, 50)，图片中心在 (0,0)。缩放后，鼠标指向的图内点不变。

        鼠标相对图片中心 = (100, 50)。缩放 1.1 倍后，这个点应移到
        (100*1.1, 50*1.1) 处，因此图片中心（偏移）要反向移动，
        使得「鼠标位置 - 新偏移」= 原来相对向量的 1.1 倍。
        """
        旧缩放 = 1.0
        鼠标 = (100.0, 50.0)
        新缩放, 新偏移 = 围绕鼠标缩放(旧缩放, (0.0, 0.0), 鼠标[0], 鼠标[1], +1)
        # 缩放后，鼠标指向的图内点（相对图片中心）应 = 原来 × 比例
        相对 = (鼠标[0] - 新偏移[0], 鼠标[1] - 新偏移[1])
        期望 = (鼠标[0] * (新缩放 / 旧缩放), 鼠标[1] * (新缩放 / 旧缩放))
        self.assertAlmostEqual(相对[0], 期望[0], places=9)
        self.assertAlmostEqual(相对[1], 期望[1], places=9)

    def test_拖动直接累加位移(self):
        偏移 = 拖动偏移((10, 20), (100, 100), (130, 150))
        self.assertEqual(偏移, (40, 70))

    def test_拖动可以让图片移出显示区(self):
        """偏移可以很大，表示图片被移出画布——这是需求 2。"""
        偏移 = 拖动偏移((0, 0), (100, 100), (2000, -3000))
        self.assertGreater(偏移[0], 1000)
        self.assertLess(偏移[1], -1000)

    def test_连续缩放后拖回中心(self):
        """缩放 + 拖动组合：先缩放再反向拖动，偏移能回到 0 附近。"""
        缩放, 偏移 = 围绕鼠标缩放(1.0, (0, 0), 50, 50, +1)
        # 鼠标在 (50,50)，图片中心 (0,0)，缩放后中心应移向鼠标的反向
        新偏移 = 拖动偏移(偏移, (50, 50), (50 - 偏移[0], 50 - 偏移[1]))
        self.assertAlmostEqual(新偏移[0], 0.0, places=9)
        self.assertAlmostEqual(新偏移[1], 0.0, places=9)


if __name__ == '__main__':
    unittest.main()
