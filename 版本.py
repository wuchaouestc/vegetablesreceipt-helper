"""软件版本号 —— 全软件唯一来源。

为什么单独一个文件
------------------
改造前版本号硬编码在 5 处，而且数字互相矛盾：窗口标题写 v6.1、关于卡片写 V6.1、
打印作业名写 V6、软著材料写 V6.0。发布时无法回答"这到底是哪一版"。

现在所有对外显示版本的地方都读这里，改版本只改一行。

注意区分三类"版本"
------------------
1. **软件版本**（本文件）：对外发布号，形如 6.3。窗口标题、关于、打印作业名、
   exe 文件属性、软著材料页眉都用它。
2. **配置格式版本**（`app.app_settings.版本` = `'4.0'`）：`settings.json` 的结构版本，
   用于判断旧配置能否直接读。
3. **数据格式版本**（`app.标签余量.版本号`、`handwriting.__version__`）：
   各自文件/子系统的内部版本。

三者互不替代，改软件版本时**不要**顺手改后两个。

改版本时要同步的地方
--------------------
除本文件外还有一处**无法自动读取**：`版本信息.txt`（PyInstaller 的 exe 版本资源，
是纯文本字面量，构建工具不会执行 Python）。改版本时请一并改它的
`filevers` / `prodvers` / `FileVersion` / `ProductVersion` 四个字段。
"""

