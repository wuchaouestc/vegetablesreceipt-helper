# -*- coding: utf-8 -*-
"""标签余量 —— 算出来的，不是量出来的。

为什么是「算」不是「量」
    佳博 GP-1326D 是热敏机，只有一个**间隙传感器**（找两张标签之间的缝，
    定位用的），**没有任何「还剩多少纸」的传感器**。TSPL 指令集里也没有
    「查询剩余介质」这一条。所以屏幕上那个数字只能是数出来的。

为什么数得准
    `label_bitmap.py` 每个作业的结尾是 `PRINT 1,1`（打 1 份）。
    一个作业**永远等于一张标签** —— 指令里没有再插 FEED，机器打完就自己
    走到下一张的缝上。所以「发了几个作业」＝「机器吃了多少张」。

为什么还是会漂
    下面这些吃纸的事，软件**完全看不见**，所以真实用量只会**比计数多**：

        开机 / 合盖自动校准        1~3 张
        手动按走纸键               1 张
        卡纸后重新装纸             1~2 张
        卷尾粘在纸芯上撕不下来     2~5 张
        断电时作业已发但没出纸     0~1 张   ← 这个反过来，计了但没打

    ⇒ 漂的方向是**乐观**：显示「还剩 200」，实际只剩 30。
    ⇒ 所以本文件有一条铁律：**宁可报少，不可报多。**
       显示时先扣掉一笔「损耗预留」（默认 5 张），并且永远向下取整。

三个能用的数字来源，可靠度递减
    ① 打印机自己报「纸用完了」—— 唯一是真的，但只告诉你「结束了」。
       `print_via_usb` 是**只写不读**的（声明了 WriteFile，没有 ReadFile）。
       **实测过了：这条路走不通。** 直连 USB 读写试了 53 次只有 3 次收到字节、
       且一次都没能复现；走 Windows 后台 `ReadPrinter` 四条查询全部 err=6，
       而同句柄的 `GetPrinter` 是成功的 ⇒ **端口不给读**。结论：这台机器问不出状态。
    ② 人 —— 最准，但要在对的时候问。
    ③ 软件数 —— 永远有，但会漂。**← 就是本文件**

本文件只管 ③：不碰界面、不碰打印、不碰硬件。
上层只要在每发出一个作业之后调一次 `记一张()`，在点打印之前调一次
`掂量(批量)`，就够了。
"""

from __future__ import annotations

import json
import os
import shutil
import tempfile
from datetime import datetime
from pathlib import Path

import 路径

HERE = 路径.程序目录()
状态文件 = HERE / '标签余量.json'

默认每卷张数 = 800
默认损耗预留 = 50
阈值_该备纸 = 30      # 低于这个数提醒「该备纸了」
阈值_没余量 = 200     # ？（保留原常量，实际以掂量返回的等级为准）
阈值_提醒黄 = 100
阈值_提醒红 = 30

版本号 = 1


def 现在():
    return datetime.now().strftime('%Y-%m-%d %H:%M:%S')


def 出厂():
    """返回一份全新的出厂状态。"""
    return {
        '版本': 版本号,
        '每卷张数': 默认每卷张数,
        '损耗预留': 默认损耗预留,
        '已用张数': 0,              # 本卷已发出的作业数
        '换卷时间': 现在(),
        '历史': [],                  # 旧卷归档
        '没纸标记': False,           # 人/机器报「没纸了」
        '实测剩余': None,            # 人直接数出来的，压过推算
    }


def 用文件(路径):
    """换一个状态文件。**只有核验脚本会调它**，生产代码不调。"""
    global 状态文件
    状态文件 = Path(路径)


def 补齐(生):
    """老文件缺字段、字段类型不对，都在这里兜住。"""
    底 = 出厂()
    if not isinstance(生, dict):
        return 底
    for k in ('每卷张数', '损耗预留', '已用张数'):
        try:
            底[k] = int(生.get(k, 底[k]))
        except (TypeError, ValueError):
            pass
    for k in ('没纸标记',):
        底[k] = bool(生.get(k, 底[k]))
    底['历史'] = list(生.get('历史', []) or [])
    实测 = 生.get('实测剩余')
    底['实测剩余'] = int(实测) if 实测 is not None else None
    底['换卷时间'] = str(生.get('换卷时间', 底['换卷时间']))
    return 底


def 读():
    """读状态。

    **任何情况下都不抛异常。** 余量只是个提醒；绝不能因为它自己读不出来
    就把打印搞崩 —— 那是拿提醒去换主营业务。
    """
    try:
        if 状态文件.is_file():
            with 状态文件.open('r', encoding='utf-8') as f:
                return 补齐(json.load(f))
    except Exception:
        pass
    return 出厂()


def 写(状态):
    """先写临时文件再原子改名 —— 断电时要么是旧的、要么是新的，不会半截。"""
    try:
        fd, 临时 = tempfile.mkstemp(dir=str(HERE), suffix='.tmp')
        os.close(fd)
        with open(临时, 'w', encoding='utf-8') as f:
            json.dump(状态, f, ensure_ascii=False, indent=2)
        os.replace(临时, 状态文件)
        return True
    except Exception:
        return False


def _算剩余(状态):
    """估算还剩几张。**永远向下取整、永远不小于 0。**"""
    每卷 = 状态.get('每卷张数', 默认每卷张数)
    用 = 状态.get('已用张数', 0)
    剩 = 每卷 - 用
    return max(0, int(剩))


def 还剩多少(状态):
    return _算剩余(状态)


def 徽章(状态):
    """平时显示在屏幕上的那一句短话。"""
    剩 = _算剩余(状态)
    if 状态.get('没纸标记'):
        return '没纸了'
    if 剩 <= 阈值_提醒红:
        return '快没了(%d)' % 剩
    if 剩 <= 阈值_提醒黄:
        return '剩 %d' % 剩
    return '%d' % 剩


def 掂量(批量, 状态):
    """点打印之前问它：这批够不够？

    返回 等级 / 剩余 / 差几张 / 文案 / 能打。
    **只给结论和建议，不拦人** —— 拦不拦是界面的事，这里不下命令。
    """
    剩 = _算剩余(状态)
    预留 = int(状态.get('损耗预留', 默认损耗预留))
    可用 = max(0, 剩 - 预留)          # 扣损耗预留，宁可报少
    差 = max(0, 批量 - 可用)
    if 状态.get('没纸标记'):
        return {'等级': '没纸', '剩余': 剩, '差': 批量, '文案': '纸用完了', '能打': False}
    if 可用 >= 批量:
        等级 = '够'
        文案 = '够打（估算剩 %d，扣预留后 %d）' % (剩, 可用)
    elif 剩 >= 批量:
        等级 = '偏紧'
        文案 = '偏紧：估算剩 %d，扣预留后 %d，这批 %d 张' % (剩, 可用, 批量)
    else:
        等级 = '不够'
        文案 = '不够：估算剩 %d，这批要 %d，差 %d 张' % (剩, 批量, 差)
    return {'等级': 等级, '剩余': 剩, '差': 差, '文案': 文案, '能打': 可用 >= 批量}


def 自检(状态):
    """设置页那一行。"""
    剩 = _算剩余(状态)
    return '每卷 %d 张，已用 %d，估剩 %d' % (
        int(状态.get('每卷张数', 默认每卷张数)),
        int(状态.get('已用张数', 0)), 剩)


def 记一张(n, 状态):
    """每发出一个作业就调一次。

    ⚠️ 不管这张**到底有没有打出来**都要计 —— 中断时我们并不知道纸出没出，
       多计一张只是让剩余偏少（安全的那一边），漏计一张就会让它偏多。
    """
    状态['已用张数'] = int(状态.get('已用张数', 0)) + int(n)
    写(状态)
    return 状态


def 补记(n):
    """人看见机器自己走纸了（开机校准、手动按键、卡纸重装）——
    软件看不见，只能让人点一下补上。**这是整套设计里最值钱的零件。**
    """
    状态 = 读()
    状态['已用张数'] = int(状态.get('已用张数', 0)) + int(n)
    写(状态)
    return 状态


def 实测(剩):
    """人直接数了还剩几张，填进来。填了就压过推算，直到下次换卷。"""
    状态 = 读()
    状态['实测剩余'] = int(剩)
    写(状态)
    return 状态


def 标没纸了():
    """打失败了、或者人说「这台已经空了」—— 收口，之后每次都提醒。"""
    状态 = 读()
    状态['没纸标记'] = True
    写(状态)
    return 状态


def 设置(每卷张数, 损耗预留):
    状态 = 读()
    状态['每卷张数'] = int(每卷张数)
    状态['损耗预留'] = int(损耗预留)
    写(状态)
    return 状态


def 换新卷(张数):
    """人点「我换新卷了」。旧卷归档进历史，计数归零。"""
    状态 = 读()
    旧 = {
        '每卷张数': int(状态.get('每卷张数', 默认每卷张数)),
        '已用张数': int(状态.get('已用张数', 0)),
        '换卷时间': 状态.get('换卷时间'),
        '归档时间': 现在(),
    }
    状态['历史'] = (状态.get('历史') or []) + [旧]
    状态['每卷张数'] = int(张数)
    状态['已用张数'] = 0
    状态['实测剩余'] = None
    状态['没纸标记'] = False
    状态['换卷时间'] = 现在()
    写(状态)
    return 状态


def 恢复出厂():
    状态 = 出厂()
    写(状态)
    return 状态


if __name__ == '__main__':
    import sys
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(encoding='utf-8')
    s = 读()
    print('状态文件：', 状态文件)
    print(json.dumps(s, ensure_ascii=False, indent=2))
